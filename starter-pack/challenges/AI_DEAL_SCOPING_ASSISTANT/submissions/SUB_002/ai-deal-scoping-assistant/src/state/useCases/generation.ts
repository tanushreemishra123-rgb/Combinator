/**
 * Generation use cases (spec sections 2-5): generate one stage, the whole pipeline, or only what a
 * change made stale. A multi-stage run threads the session through local variables and saves after
 * every stage, so a failure half-way keeps what was already generated and never re-reads state that
 * React has not committed yet. Stages that are 'current' are never touched by a stale refresh.
 */
import { resolveRunOptions } from '../../ai';
import type { AiSettings } from '../../ai';
import type { GenerationMeta, ScopingSession, SectionState, SessionOutputs } from '../../domain';
import { stageState } from '../../impact';
import { stagePrerequisite } from '../stageRules';
import type { StageId, UseCaseDeps } from '../types';
import { estimateNeedsOnlyRecalculation, recalculateEstimateStage } from './estimateRecalc';
import { busyLabelFor, runStage, STAGE_ORDER, stageLabel } from './stageRunner';
import { describeError, notify, notifyFallback, requireActiveSession, saveSession } from './support';

/** What happened to one stage: `meta` is null when the deterministic engine recalculated it without AI. */
interface StageOutcome {
  stageId: StageId;
  session: ScopingSession;
  meta: GenerationMeta | null;
}

type StageStep = (session: ScopingSession, stageId: StageId) => Promise<StageOutcome>;

/** Generates and saves one stage; throws when its prerequisite is missing or the provider fails. */
async function generateAndSave(deps: UseCaseDeps, session: ScopingSession, stageId: StageId, aiSettings: AiSettings): Promise<StageOutcome> {
  deps.dispatch({ type: 'START_BUSY', label: busyLabelFor(stageId), stageId });
  const run = resolveRunOptions(aiSettings, session.scope?.version ?? 0);
  const result = await runStage(session, stageId, run);
  return { stageId, session: saveSession(deps, result.session), meta: result.meta };
}

/** The estimate is recalculated by the engine alone when no pending change needs the AI stage. */
async function refreshStage(deps: UseCaseDeps, session: ScopingSession, stageId: StageId, aiSettings: AiSettings): Promise<StageOutcome> {
  if (stageId === 'estimate' && estimateNeedsOnlyRecalculation(session)) {
    deps.dispatch({ type: 'START_BUSY', label: 'Recalculating the estimate...', stageId });
    return { stageId, session: saveSession(deps, recalculateEstimateStage(session, deps.now())), meta: null };
  }
  return generateAndSave(deps, session, stageId, aiSettings);
}

function describeOutcome(outcome: StageOutcome): string {
  const label = stageLabel(outcome.stageId);
  return outcome.meta === null ? `${label}: recalculated by the calculation engine (no AI call)` : `${label}: generated by ${outcome.meta.providerLabel}`;
}

function countValidationNotes(outcomes: readonly StageOutcome[]): number {
  return outcomes.flatMap((outcome) => outcome.meta?.issues ?? []).filter((issue) => issue.code !== 'live-fallback').length;
}

/** One success notice naming the path that produced each stage, plus a warning per live-AI fallback. */
function notifyOutcomes(deps: UseCaseDeps, outcomes: readonly StageOutcome[]): void {
  const first = outcomes.at(0);
  if (first === undefined) {
    return;
  }
  const verb = first.meta === null ? 'recalculated' : 'generated';
  const title = outcomes.length === 1 ? `${stageLabel(first.stageId)} ${verb}` : `${outcomes.length} deliverables brought up to date`;
  const notes = countValidationNotes(outcomes);
  const notesSentence = notes === 0 ? '' : ` ${notes} validation note(s) were recorded - see the generation details of each section.`;
  notify(deps, 'success', title, `${outcomes.map(describeOutcome).join('; ')}.${notesSentence}`);
  for (const outcome of outcomes) {
    if (outcome.meta !== null) {
      notifyFallback(deps, stageLabel(outcome.stageId), outcome.meta);
    }
  }
}

/**
 * Runs the given stages in dependency order, threading the session from one stage into the next,
 * and stops at the first failure with an error notice that names the stage. Stages completed
 * before a failure stay saved.
 */
async function runStagesInOrder(deps: UseCaseDeps, start: ScopingSession, stageIds: readonly StageId[], step: StageStep): Promise<void> {
  const outcomes: StageOutcome[] = [];
  let session = start;
  try {
    for (const stageId of stageIds) {
      try {
        const outcome = await step(session, stageId);
        outcomes.push(outcome);
        session = outcome.session;
      } catch (error) {
        notify(deps, 'error', `${stageLabel(stageId)} failed`, describeError(error));
        break;
      }
    }
  } finally {
    deps.dispatch({ type: 'END_BUSY' });
  }
  notifyOutcomes(deps, outcomes);
}

/** Generates (or regenerates) one stage of the active session after checking its prerequisite. */
export async function generateStage(deps: UseCaseDeps, stageId: StageId): Promise<void> {
  const session = requireActiveSession(deps);
  if (session === null) {
    return;
  }
  const prerequisite = stagePrerequisite(session, stageId);
  if (prerequisite !== null) {
    notify(deps, 'error', `${stageLabel(stageId)} cannot be generated yet`, prerequisite);
    return;
  }
  const { aiSettings } = deps.getState();
  await runStagesInOrder(deps, session, [stageId], (current, id) => generateAndSave(deps, current, id, aiSettings));
}

/** Generates every stage: PRD -> architecture -> data and integration -> AI approach -> estimate. */
export async function generateAll(deps: UseCaseDeps): Promise<void> {
  const session = requireActiveSession(deps);
  if (session === null) {
    return;
  }
  const prerequisite = stagePrerequisite(session, 'prd');
  if (prerequisite !== null) {
    notify(deps, 'error', 'Deliverables cannot be generated yet', prerequisite);
    return;
  }
  const { aiSettings } = deps.getState();
  await runStagesInOrder(deps, session, STAGE_ORDER, (current, id) => generateAndSave(deps, current, id, aiSettings));
}

/** Why the stale stages cannot be refreshed yet; an engine-only recalculation never needs approval. */
function refreshBlocker(session: ScopingSession, staleStages: readonly StageId[]): string | null {
  const needsAi = staleStages.filter((stageId) => !(stageId === 'estimate' && estimateNeedsOnlyRecalculation(session)));
  const first = needsAi.at(0);
  return first === undefined ? null : stagePrerequisite(session, first);
}

/**
 * Regenerates or recalculates the stale stages, in dependency order. Current stages are left
 * exactly as they are - same object, same reviewed flag - so reviewed, unaffected content survives.
 * With `onlyStageId` (spec 6: the reviewer regenerates "the affected sections", not everything at
 * once), only that one stage is touched even when other stages are also stale; a Pending-updates
 * row passes its own stage id here instead of triggering every stale stage at once.
 */
export async function regenerateStale(deps: UseCaseDeps, onlyStageId?: StageId): Promise<void> {
  const session = requireActiveSession(deps);
  if (session === null) {
    return;
  }
  const allStale = STAGE_ORDER.filter((stageId) => stageState(session.outputs, stageId).status === 'stale');
  const staleStages = onlyStageId === undefined ? allStale : allStale.filter((stageId) => stageId === onlyStageId);
  if (staleStages.length === 0) {
    const subject = onlyStageId === undefined ? 'Every generated deliverable' : stageLabel(onlyStageId);
    notify(deps, 'info', 'Nothing to regenerate', `${subject} is already up to date.`);
    return;
  }
  const blocker = refreshBlocker(session, staleStages);
  if (blocker !== null) {
    notify(deps, 'error', 'Stale deliverables cannot be regenerated yet', blocker);
    return;
  }
  const { aiSettings } = deps.getState();
  await runStagesInOrder(deps, session, staleStages, (current, id) => refreshStage(deps, current, id, aiSettings));
}

function withReviewed<T>(state: SectionState<T>, reviewed: boolean): SectionState<T> {
  return { ...state, reviewed };
}

function withStageReviewed(outputs: SessionOutputs, stageId: StageId, reviewed: boolean): SessionOutputs {
  switch (stageId) {
    case 'prd':
      return { ...outputs, prd: withReviewed(outputs.prd, reviewed) };
    case 'architecture':
      return { ...outputs, architecture: withReviewed(outputs.architecture, reviewed) };
    case 'dataIntegration':
      return { ...outputs, dataIntegration: withReviewed(outputs.dataIntegration, reviewed) };
    case 'aiStrategy':
      return { ...outputs, aiStrategy: withReviewed(outputs.aiStrategy, reviewed) };
    case 'estimate':
      return { ...outputs, estimate: withReviewed(outputs.estimate, reviewed) };
  }
}

/** Records the reviewer's sign-off on a generated stage; it is cleared only when that stage is regenerated. */
export function setStageReviewed(deps: UseCaseDeps, stageId: StageId, reviewed: boolean): void {
  const session = requireActiveSession(deps);
  if (session === null) {
    return;
  }
  if (stageState(session.outputs, stageId).data === null) {
    notify(deps, 'error', 'Nothing to review yet', `${stageLabel(stageId)} has not been generated, so it cannot be marked as reviewed.`);
    return;
  }
  saveSession(deps, { ...session, outputs: withStageReviewed(session.outputs, stageId, reviewed) });
}
