/**
 * Runs a task through a provider and the shared pipeline: prompt -> provider -> JSON extraction ->
 * Zod validation -> `GenerationMeta`. A live-mode schema failure gets one corrective retry; if that
 * (or the provider call itself) still fails, `options.fallback` (the mock provider) takes over and
 * the failure is recorded as a warning `ValidationIssue` rather than reported silently.
 */
import type { z } from 'zod';
import type { ValidationIssue } from '../domain';
import { extractJson } from './jsonExtraction';
import type { AiProvider, AiRequest, AiTaskContext, PromptParts, TaskDefinition, TaskResult, TaskRunOptions } from './types';
import { AiProviderError } from './types';

/** Converts Zod issues into `ValidationIssue`s (code `schema`), the field path folded into the message. */
export function zodIssuesToValidationIssues(error: z.ZodError): ValidationIssue[] {
  return error.issues.map((issue) => ({
    severity: 'warning',
    code: 'schema',
    message: issue.path.length > 0 ? `${issue.path.join('.')}: ${issue.message}` : issue.message,
    refs: [],
  }));
}

function describeZodIssues(error: z.ZodError): string {
  return zodIssuesToValidationIssues(error)
    .map((issue) => issue.message)
    .join('; ');
}

function describeFailure(error: unknown): string {
  if (error instanceof AiProviderError) {
    return `${error.kind}: ${error.message}`;
  }
  return error instanceof Error ? error.message : 'an unknown error';
}

function buildCorrectivePrompt(request: AiRequest, zodError: z.ZodError): AiRequest {
  const correctivePrompt = [
    request.prompt,
    '',
    'Your previous response failed schema validation with the following issues:',
    describeZodIssues(zodError),
    'Return a single corrected JSON object that fixes every issue above, and nothing else.',
  ].join('\n');
  return { ...request, prompt: correctivePrompt };
}

type AttemptResult<T> = { success: true; value: T } | { success: false; zodError: z.ZodError };

async function attemptTask<C extends AiTaskContext, T>(
  provider: AiProvider,
  request: AiRequest,
  task: TaskDefinition<C, T>,
): Promise<AttemptResult<T>> {
  const raw = await provider.complete(request);
  const parsed = extractJson(raw);
  const result = task.schema.safeParse(parsed);
  return result.success ? { success: true, value: result.data } : { success: false, zodError: result.error };
}

/** A schema failure from the mock provider is a bug in that provider's planner, not a data problem - throw. */
async function runMockTask<C extends AiTaskContext, T>(provider: AiProvider, request: AiRequest, task: TaskDefinition<C, T>): Promise<T> {
  const result = await attemptTask(provider, request, task);
  if (result.success) {
    return result.value;
  }
  throw new Error(`Mock provider "${provider.id}" returned data that failed validation for task "${task.id}": ${describeZodIssues(result.zodError)}`);
}

/** One corrective retry on a live-mode schema failure, listing the Zod issues back to the model. */
async function runLiveTaskWithRetry<C extends AiTaskContext, T>(
  provider: AiProvider,
  request: AiRequest,
  task: TaskDefinition<C, T>,
): Promise<AttemptResult<T>> {
  const first = await attemptTask(provider, request, task);
  if (first.success) {
    return first;
  }
  return attemptTask(provider, buildCorrectivePrompt(request, first.zodError), task);
}

function buildResult<T>(value: T, provider: AiProvider, usedFallback: boolean, issues: ValidationIssue[], scopeVersion: number, startedAt: number): TaskResult<T> {
  return {
    value,
    meta: {
      providerId: provider.id,
      providerLabel: provider.label,
      mode: provider.mode,
      usedFallback,
      generatedAt: new Date().toISOString(),
      durationMs: Math.round(performance.now() - startedAt),
      scopeVersion,
      issues,
    },
  };
}

async function runFallback<C extends AiTaskContext, T>(
  options: TaskRunOptions,
  request: AiRequest,
  task: TaskDefinition<C, T>,
  zodError: z.ZodError | undefined,
  reason: string,
  startedAt: number,
): Promise<TaskResult<T>> {
  if (options.fallback === null) {
    throw new AiProviderError('invalid-response', `The live AI provider failed and no fallback is configured: ${reason}`);
  }
  const value = await runMockTask(options.fallback, request, task);
  const issues = zodError === undefined ? [] : zodIssuesToValidationIssues(zodError);
  issues.push({
    severity: 'warning',
    code: 'live-fallback',
    message: `The live AI provider could not produce a usable result (${reason}), so this section was generated by ${options.fallback.label} instead.`,
    refs: [],
  });
  return buildResult(value, options.fallback, true, issues, options.scopeVersion, startedAt);
}

/** Builds the prompt, calls the provider, extracts JSON and validates it against `task.schema`. */
export async function runTask<C extends AiTaskContext, T>(task: TaskDefinition<C, T>, context: C, options: TaskRunOptions): Promise<TaskResult<T>> {
  const startedAt = performance.now();
  const request: AiRequest = { ...task.buildPrompt(context), context };

  if (options.provider.mode !== 'live') {
    const value = await runMockTask(options.provider, request, task);
    return buildResult(value, options.provider, false, [], options.scopeVersion, startedAt);
  }

  try {
    const attempt = await runLiveTaskWithRetry(options.provider, request, task);
    if (attempt.success) {
      return buildResult(attempt.value, options.provider, false, [], options.scopeVersion, startedAt);
    }
    return await runFallback(options, request, task, attempt.zodError, describeZodIssues(attempt.zodError), startedAt);
  } catch (error) {
    return runFallback(options, request, task, undefined, describeFailure(error), startedAt);
  }
}

async function requestText(provider: AiProvider, request: AiRequest): Promise<string> {
  const raw = await provider.complete(request);
  const trimmed = raw.trim();
  if (trimmed.length > 0) {
    return trimmed;
  }
  if (provider.mode !== 'live') {
    throw new Error(`Mock provider "${provider.id}" returned an empty response for a text task.`);
  }
  throw new AiProviderError('invalid-response', 'The AI response was empty.');
}

/** Same pipeline as `runTask`, minus JSON parsing: returns trimmed, non-empty text. */
export async function runTextTask<C extends AiTaskContext>(
  task: { id: C['task']; label: string; buildPrompt(context: C): PromptParts },
  context: C,
  options: TaskRunOptions,
): Promise<TaskResult<string>> {
  const startedAt = performance.now();
  const request: AiRequest = { ...task.buildPrompt(context), context };

  try {
    const text = await requestText(options.provider, request);
    return buildResult(text, options.provider, false, [], options.scopeVersion, startedAt);
  } catch (error) {
    if (options.provider.mode !== 'live') {
      throw error;
    }
    if (options.fallback === null) {
      throw error instanceof AiProviderError ? error : new AiProviderError('invalid-response', describeFailure(error));
    }
    const fallbackText = await requestText(options.fallback, request);
    const issues: ValidationIssue[] = [
      {
        severity: 'warning',
        code: 'live-fallback',
        message: `The live AI provider could not produce a usable result (${describeFailure(error)}), so this section was generated by ${options.fallback.label} instead.`,
        refs: [],
      },
    ];
    return buildResult(fallbackText, options.fallback, true, issues, options.scopeVersion, startedAt);
  }
}
