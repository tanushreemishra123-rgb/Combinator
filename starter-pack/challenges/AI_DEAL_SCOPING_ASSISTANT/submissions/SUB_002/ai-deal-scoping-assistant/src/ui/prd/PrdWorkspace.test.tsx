/**
 * Behaviour tests for the PRD and Scope Workspace root: prerequisite gating, generation, the
 * reviewed toggle, the stale banner, busy state, tab switching and cross-workspace navigation.
 * The state layer is mocked (fixed contract, see src/state/index.ts) so these tests never depend
 * on another engineer's in-progress use-case or selector bodies.
 */
import { fireEvent, render, screen, within } from '@testing-library/react';
import type { ScopingSession } from '../../domain';
import { fixtureSession } from '../../test/fixtures';
import { NavigationContext } from '../navigation';
import type { WorkspaceNavigation } from '../navigation';
import { PrdWorkspace } from './PrdWorkspace';
import { fixtureCoverageReport, fixtureGenerationMeta, fixturePrdBundle, fixtureStageStatus } from './prdFixtures';

const { mockUseActiveSession, mockUseActions, mockUseBusy, mockSelectStageStatuses, mockSelectCoverage } = vi.hoisted(() => ({
  mockUseActiveSession: vi.fn(),
  mockUseActions: vi.fn(),
  mockUseBusy: vi.fn(),
  mockSelectStageStatuses: vi.fn(),
  mockSelectCoverage: vi.fn(),
}));

vi.mock('../../state', () => ({
  useActiveSession: mockUseActiveSession,
  useActions: mockUseActions,
  useBusy: mockUseBusy,
  selectStageStatuses: mockSelectStageStatuses,
  selectCoverage: mockSelectCoverage,
}));

const actions = {
  generateStage: vi.fn(),
  setStageReviewed: vi.fn(),
};

function sessionWithPrd(overrides: Partial<ScopingSession['outputs']['prd']> = {}): ScopingSession {
  const session = fixtureSession();
  return {
    ...session,
    outputs: {
      ...session.outputs,
      prd: { data: null, status: 'empty', reviewed: false, meta: null, staleReasons: [], ...overrides },
    },
  };
}

function renderWorkspace(navigate: (workspace: string, focusId?: string) => void = vi.fn()) {
  const navigation: WorkspaceNavigation = { activeWorkspace: 'prd', focusId: null, navigate, clearFocus: vi.fn() };
  return render(
    <NavigationContext.Provider value={navigation}>
      <PrdWorkspace />
    </NavigationContext.Provider>,
  );
}

beforeEach(() => {
  vi.clearAllMocks();
  mockUseActions.mockReturnValue(actions);
  mockUseBusy.mockReturnValue(null);
  mockSelectCoverage.mockReturnValue(fixtureCoverageReport());
});

describe('PrdWorkspace - no session / stage lookup failure', () => {
  it('shows an empty state when there is no active session', () => {
    mockUseActiveSession.mockReturnValue(null);
    renderWorkspace();
    expect(screen.getByText('No active session')).toBeInTheDocument();
    expect(screen.getByText('Create or open a scoping session to work on its PRD.')).toBeInTheDocument();
  });

  it('shows an error callout when the PRD stage status cannot be found', () => {
    mockUseActiveSession.mockReturnValue(sessionWithPrd());
    mockSelectStageStatuses.mockReturnValue([]);
    renderWorkspace();
    expect(screen.getByText('PRD stage unavailable')).toBeInTheDocument();
  });
});

describe('PrdWorkspace - prerequisite gating', () => {
  it('disables generation and surfaces the prerequisite message when the scope is not approved', () => {
    mockUseActiveSession.mockReturnValue(sessionWithPrd());
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus({ prerequisite: 'Approve the scope before generating the PRD.' })]);
    renderWorkspace();

    expect(screen.getByRole('button', { name: 'Generate the PRD' })).toBeDisabled();
    expect(screen.getAllByText('Approve the scope before generating the PRD.').length).toBeGreaterThan(0);
  });

  it('never shows a blank panel when the PRD has not been generated yet', () => {
    mockUseActiveSession.mockReturnValue(sessionWithPrd());
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus()]);
    renderWorkspace();
    expect(screen.getByText('Nothing generated yet')).toBeInTheDocument();
  });
});

describe('PrdWorkspace - generation', () => {
  it('generates the PRD when the prerequisite is met', () => {
    mockUseActiveSession.mockReturnValue(sessionWithPrd());
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus()]);
    renderWorkspace();

    fireEvent.click(screen.getByRole('button', { name: 'Generate the PRD' }));
    expect(actions.generateStage).toHaveBeenCalledWith('prd');
  });

  it('shows the generation meta line, reviewed toggle and switches the action label to Regenerate once data exists', () => {
    const meta = fixtureGenerationMeta();
    mockUseActiveSession.mockReturnValue(sessionWithPrd({ data: fixturePrdBundle(), status: 'current', meta }));
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus({ status: 'current' })]);
    renderWorkspace();

    expect(screen.getByRole('button', { name: 'Regenerate the PRD' })).toBeInTheDocument();
    expect(screen.getByText(/Generated by Mock Heuristic Engine \(Mock AI\)/)).toBeInTheDocument();
    expect(screen.getByLabelText('Mark as reviewed')).toBeInTheDocument();
  });

  it('toggles the reviewed flag', () => {
    mockUseActiveSession.mockReturnValue(sessionWithPrd({ data: fixturePrdBundle(), status: 'current', meta: fixtureGenerationMeta() }));
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus({ status: 'current', reviewed: false })]);
    renderWorkspace();

    fireEvent.click(screen.getByLabelText('Mark as reviewed'));
    expect(actions.setStageReviewed).toHaveBeenCalledWith('prd', true);
  });

  it('shows a stale banner with reasons and regenerates from its action', () => {
    mockUseActiveSession.mockReturnValue(
      sessionWithPrd({ data: fixturePrdBundle(), status: 'stale', meta: fixtureGenerationMeta(), staleReasons: ['Requirement FR_02 changed after this section was generated.'] }),
    );
    mockSelectStageStatuses.mockReturnValue([
      fixtureStageStatus({ status: 'stale', staleReasons: ['Requirement FR_02 changed after this section was generated.'] }),
    ]);
    renderWorkspace();

    const staleBanner = screen.getByText('This section is out of date').closest('div.stale-banner') as HTMLElement;
    expect(within(staleBanner).getByText('Requirement FR_02 changed after this section was generated.')).toBeInTheDocument();

    fireEvent.click(within(staleBanner).getByRole('button', { name: 'Regenerate the PRD' }));
    expect(actions.generateStage).toHaveBeenCalledWith('prd');
  });

  it('shows generation notes when validation issues were recorded', () => {
    const meta = fixtureGenerationMeta({ issues: [{ severity: 'warning', code: 'unresolved-ref', message: 'Capability CAP_02 cites an unknown requirement.', refs: [] }] });
    mockUseActiveSession.mockReturnValue(sessionWithPrd({ data: fixturePrdBundle(), status: 'current', meta }));
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus({ status: 'current' })]);
    renderWorkspace();

    expect(screen.getByText('Generation notes (1)')).toBeInTheDocument();
    fireEvent.click(screen.getByText('Generation notes (1)'));
    expect(screen.getByText('Capability CAP_02 cites an unknown requirement.')).toBeInTheDocument();
  });

  it('shows the busy overlay while the PRD is generating', () => {
    mockUseActiveSession.mockReturnValue(sessionWithPrd());
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus()]);
    mockUseBusy.mockReturnValue({ label: 'Generating the PRD...', stageId: 'prd' });
    renderWorkspace();

    expect(screen.getAllByText('Generating the PRD...').length).toBeGreaterThan(0);
    expect(screen.getByRole('button', { name: /Generate the PRD/ })).toBeDisabled();
  });
});

describe('PrdWorkspace - tabs and navigation', () => {
  function renderWithData(navigate?: (workspace: string, focusId?: string) => void) {
    mockUseActiveSession.mockReturnValue(sessionWithPrd({ data: fixturePrdBundle(), status: 'current', meta: fixtureGenerationMeta() }));
    mockSelectStageStatuses.mockReturnValue([fixtureStageStatus({ status: 'current' })]);
    return renderWorkspace(navigate);
  }

  it('shows the Product Requirements Document tab by default with all 14 sections outlined', () => {
    renderWithData();
    expect(screen.getByRole('tab', { name: 'Product Requirements Document', selected: true })).toBeInTheDocument();
    expect(screen.getByRole('navigation', { name: 'Product Requirements Document sections' })).toBeInTheDocument();
  });

  it('switches to the Functional Scope tab and shows the label legend and capability cards', () => {
    renderWithData();
    fireEvent.click(screen.getByRole('tab', { name: 'Functional Scope' }));
    expect(screen.getByText('Identity, Sign-In and Profile Management')).toBeInTheDocument();
    expect(screen.getByText('Label legend')).toBeInTheDocument();
    expect(screen.getByText('Recommended enhancements')).toBeInTheDocument();
  });

  it('switches to the Requirement Coverage tab and shows the coverage tiles', () => {
    renderWithData();
    fireEvent.click(screen.getByRole('tab', { name: 'Requirement Coverage' }));
    expect(screen.getByText('Overall requirement coverage')).toBeInTheDocument();
    expect(screen.getByText('High-priority coverage')).toBeInTheDocument();
  });

  it('navigates to the Customer Requirements Workspace when a requirement chip is clicked', () => {
    const navigate = vi.fn();
    renderWithData(navigate);
    fireEvent.click(screen.getAllByRole('button', { name: 'FR_01' }).at(0) as HTMLElement);
    expect(navigate).toHaveBeenCalledWith('requirements', 'FR_01');
  });

  it('does not render its own footer nav (the app shell renders it once, see WorkspaceContainer)', () => {
    renderWithData();
    expect(screen.queryByRole('navigation', { name: 'Workspace navigation' })).not.toBeInTheDocument();
  });
});
