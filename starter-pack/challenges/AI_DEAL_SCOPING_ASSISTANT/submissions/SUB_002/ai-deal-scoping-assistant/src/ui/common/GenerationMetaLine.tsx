/** Audit line shown under every generated section: who produced it, in what mode, and when. */
import type { ReactElement } from 'react';
import type { GenerationMeta } from '../../domain';
import { formatDateTime } from './format';
import { AlertTriangleIcon, ClockIcon } from './icons';

export interface GenerationMetaLineProps {
  meta: GenerationMeta;
}

export function GenerationMetaLine({ meta }: GenerationMetaLineProps): ReactElement {
  const modeLabel = meta.mode === 'mock' ? 'Mock AI' : 'Live AI';
  return (
    <p className="generation-meta text-subtle text-xs">
      <ClockIcon size={12} />
      Generated by {meta.providerLabel} ({modeLabel}) - {formatDateTime(meta.generatedAt)}
      {meta.usedFallback ? (
        <span className="generation-meta-fallback">
          <AlertTriangleIcon size={12} />
          Live call failed - used the mock fallback
        </span>
      ) : null}
    </p>
  );
}
