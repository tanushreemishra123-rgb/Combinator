import type { PackageDocument, PackageSection } from '../domain';
import { toMarkdown } from './markdown';

function doc(sections: PackageSection[]): PackageDocument {
  return { title: 'Acme - Integrated Scoping Package', subtitle: 'Acme Corp', generatedAt: '2026-09-19T00:00:00.000Z', aiModeLabel: 'Mock AI mode', exportStatus: 'Ready', disclaimer: 'This is the mandatory disclaimer statement.', sections };
}

describe('toMarkdown', () => {
  it('renders the title, status line and disclaimer at both the top and the end', () => {
    const markdown = toMarkdown(doc([{ id: 'executive-summary', title: 'Executive summary', blocks: [{ type: 'paragraph', text: 'Summary.' }] }]));
    expect(markdown).toContain('# Acme - Integrated Scoping Package');
    expect(markdown).toContain('Ready');
    const disclaimerOccurrences = markdown.split('This is the mandatory disclaimer statement.').length - 1;
    expect(disclaimerOccurrences).toBe(2);
  });

  it('lists every section in the table of contents, linked by anchor', () => {
    const markdown = toMarkdown(doc([{ id: 'requirement-summary', title: 'Requirement summary', blocks: [{ type: 'paragraph', text: 'x' }] }]));
    expect(markdown).toContain('[Requirement summary](#requirement-summary)');
  });

  it('escapes pipe characters and newlines inside table cells', () => {
    const markdown = toMarkdown(
      doc([{ id: 'requirement-summary', title: 'Requirement summary', blocks: [{ type: 'table', columns: ['ID', 'Text'], rows: [['FR_01', 'A | B\nsecond line']] }] }]),
    );
    expect(markdown).toContain('A \\| B second line');
    expect(markdown).not.toContain('A | B\nsecond line');
  });

  it('renders headings, lists, callouts and key/value pairs', () => {
    const markdown = toMarkdown(
      doc([
        {
          id: 'assumptions',
          title: 'Assumptions',
          blocks: [
            { type: 'heading', level: 3, text: 'Sub-heading' },
            { type: 'list', items: ['One', 'Two'] },
            { type: 'callout', tone: 'warning', title: 'Not generated yet', text: 'Not generated yet - x.' },
            { type: 'keyValues', pairs: [{ key: 'Generated by', value: 'Mock AI' }] },
          ],
        },
      ]),
    );
    expect(markdown).toContain('### Sub-heading');
    expect(markdown).toContain('- One');
    expect(markdown).toContain('> **Warning - Not generated yet**');
    expect(markdown).toContain('**Generated by:** Mock AI');
  });

  it('renders a diagram block as a Mermaid code fence', () => {
    const markdown = toMarkdown(doc([{ id: 'architecture-diagram', title: 'Architecture diagram', blocks: [{ type: 'diagram', title: 'Architecture', mermaid: 'flowchart TB\n  a --> b', diagramId: 'architecture' }] }]));
    expect(markdown).toContain('```mermaid');
    expect(markdown).toContain('flowchart TB');
  });
});
