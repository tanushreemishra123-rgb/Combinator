/**
 * Text the engine adds around the numbers: the commercial assumptions that were actually used, the
 * closing explanation and the totals calculation trace. All of it is derived from the result.
 */
import { formatId } from '../../domain';
import type { EstimateNote, EstimateResult, EstimateTotals, EstimationConfig, MoneyRange, PhaseEstimate } from '../../domain';
import { formatDecimal, formatFactor, formatMoney, formatPct, formatWhole, joinList } from '../format';
import { CALCULATION_RULES } from './rules';
import { teamCapacity } from './timeline';

const ASSUMPTION_PREFIX = 'EA';
const NOTE_SEQUENCE = /^[A-Z]+_(\d+)$/;

function highestSequence(notes: readonly EstimateNote[]): number {
  return notes.reduce((max, note) => Math.max(max, Number(NOTE_SEQUENCE.exec(note.id)?.at(1) ?? 0)), 0);
}

/** Visible commercial and delivery assumptions, numbered after the suggested assumptions. */
export function commercialAssumptions(config: EstimationConfig, existing: readonly EstimateNote[]): EstimateNote[] {
  const texts = [
    `The timeline assumes an average team of ${formatDecimal(config.teamSize)} people working ${formatDecimal(config.workingDaysPerWeek)} days per week, with the build phases running concurrently.`,
    `Costs use the configured role day rates in ${config.currency}; a contingency of ${formatPct(config.contingencyPct)} is added to the subtotal and ROM values are rounded to the nearest ${formatWhole(config.roundingUnit)}.`,
    `A productivity factor of ${formatFactor(config.productivityFactor)} is applied to all build effort, and up to ${formatWhole(config.baselineEnvironments)} environments are covered before the ${formatPct(config.extraEnvironmentPct)} per-environment uplift applies.`,
  ];
  const offset = highestSequence(existing);
  return texts.map((text, index) => ({ id: formatId(ASSUMPTION_PREFIX, offset + index + 1), text, refs: [] }));
}

function rangeText(range: MoneyRange): string {
  return `${formatMoney(range.low, range.currency)} to ${formatMoney(range.high, range.currency)} (likely ${formatMoney(range.likely, range.currency)})`;
}

function commercialSentence(totals: EstimateTotals, config: EstimationConfig, blockedLabels: readonly string[]): string {
  if (totals.rom === null) {
    return `The ROM commercial range is blocked until the following inputs are provided: ${joinList(blockedLabels)}.`;
  }
  return `The ROM commercial range is ${rangeText(totals.rom)} including ${formatPct(config.contingencyPct)} contingency.`;
}

/** Suggested explanation (no numbers by contract) followed by the calculated headline figures. */
export function explainResult(result: Omit<EstimateResult, 'explanation'>, suggested: string): string {
  const { totals, configSnapshot } = result;
  const blockedLabels = result.missingInputs
    .filter((missing) => missing.effect === 'calculation-blocked')
    .map((missing) => missing.label);
  const firstRule = CALCULATION_RULES.at(0)?.id ?? '';
  const lastRule = CALCULATION_RULES.at(-1)?.id ?? '';
  const sentences = [
    suggested.trim(),
    `Calculated effort is ${formatWhole(totals.effortDays.low)} to ${formatWhole(totals.effortDays.high)} person-days (likely ${formatWhole(totals.effortDays.likely)}) over ${formatWhole(totals.timelineWeeks.low)} to ${formatWhole(totals.timelineWeeks.high)} weeks (likely ${formatWhole(totals.timelineWeeks.likely)}) with ${result.confidence} overall confidence.`,
    commercialSentence(totals, configSnapshot, blockedLabels),
    `Every figure is produced by the documented calculation rules ${firstRule} to ${lastRule} from the visible drivers and configuration; none is generated by the AI.`,
  ];
  return sentences.filter((sentence) => sentence !== '').join(' ');
}

/** Reproducible trace of the ROM totals (rule CR_11) for the Estimate Workspace and the exports. */
export function describeTotalsCalculation(result: EstimateResult): string[] {
  const { totals, configSnapshot: config } = result;
  const effortLine = `Total effort = sum of workstream ranges = ${formatWhole(totals.effortDays.low)} to ${formatWhole(totals.effortDays.high)} days (likely ${formatWhole(totals.effortDays.likely)}) = ${formatDecimal(totals.effortPersonWeeks.likely)} person-weeks at ${formatDecimal(config.workingDaysPerWeek)} days per week`;
  if (totals.subtotal === null || totals.contingency === null || totals.rom === null) {
    const blocked = result.missingInputs.filter((missing) => missing.effect === 'calculation-blocked').map((missing) => missing.label);
    return [effortLine, `ROM blocked until the missing inputs are provided: ${joinList(blocked)}`];
  }
  const rawLikely = result.workstreams.reduce((total, workstream) => total + (workstream.cost?.likely ?? 0), 0);
  return [
    effortLine,
    `Subtotal (likely) = sum of workstream costs ${formatMoney(rawLikely, config.currency)} -> rounded to ${formatWhole(config.roundingUnit)} = ${formatMoney(totals.subtotal.likely, config.currency)}`,
    `Contingency (likely) = ${formatMoney(totals.subtotal.likely, config.currency)} x ${formatPct(config.contingencyPct)} -> rounded = ${formatMoney(totals.contingency.likely, config.currency)}`,
    `ROM (likely) = subtotal + contingency = ${formatMoney(totals.rom.likely, config.currency)}`,
    `ROM range = ${rangeText(totals.rom)}; low and high are calculated the same way from the workstream low and high costs`,
  ];
}

/** One phase's own schedule trace, without repeating the shared team-capacity line already stated once above. */
function phaseTimelineLine(phase: PhaseEstimate): string {
  const steps = phase.calculation.filter((line) => !line.startsWith('Team capacity'));
  return `${phase.name} (${phase.id}) = ${steps.join('; ')}`;
}

/**
 * Reproducible trace of the timeline weeks (rule CR_12): team capacity, how each phase turns its
 * effort into a duration - the build phases sharing one concurrent window, testing overlapping the
 * end of that window, the lead and closing phases running sequentially - and the final rounding.
 */
export function describeTimelineCalculation(result: EstimateResult, config: EstimationConfig): string[] {
  const capacityLine = `Team capacity = ${formatDecimal(config.teamSize)} people x ${formatDecimal(config.workingDaysPerWeek)} working days per week = ${formatDecimal(teamCapacity(config))} person-days per week; every phase below divides its effort by this shared capacity (rule CR_12).`;
  const totalLine = `Total timeline = the last phase's end week on that shared calendar = ${formatWhole(result.totals.timelineWeeks.low)} to ${formatWhole(result.totals.timelineWeeks.high)} weeks (likely ${formatWhole(result.totals.timelineWeeks.likely)}), every phase duration rounded up to a whole week.`;
  return [capacityLine, ...result.phases.map(phaseTimelineLine), totalLine];
}
